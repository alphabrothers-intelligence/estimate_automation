-- 테스티파이 마케팅 — 런칭 마케팅 / 그로스해킹 / 퍼포먼스
-- 출처: backend/templates/testify.xlsx "시장성테스트" X13:X21 (= 우유곳간 260811 발급본).
-- 모듈별 합계가 041의 module_weight와 정확히 일치한다:
--   런칭 마케팅 3,000,000+100,000+600,000+600,000+1,000,000 = 5,300,000
--   그로스해킹  500,000×16 + 300,000×16                     = 12,800,000
--   퍼포먼스    9,000,000 + 900,000(실비의 10%)              = 9,900,000
--   합계 28,000,000 → VAT 2,800,000 → 총 30,800,000
-- 썬데이워커는 shared_source_entity_id로 테스티파이 카탈로그를 차용하므로 함께 적용된다.
-- ============================================================
update item_catalogs c set unit_price = v.price
from (values
    ('런칭 마케팅', '자사몰 구축',                3000000),
    ('런칭 마케팅', '마케팅 전략안',              100000),
    ('런칭 마케팅', 'SEO 키워드 세팅',            600000),
    ('런칭 마케팅', 'Meta 계정 및 Pixel 세팅',    600000),
    ('런칭 마케팅', '데이터 연동',                1000000),
    ('그로스해킹', '주간 Wrap-Up',                500000),
    ('그로스해킹', '주간 액션플랜 수행',          300000),
    ('퍼포먼스',   'Meta 광고 실비',              9000000),
    ('퍼포먼스',   'Meta 광고 운영',              900000)   -- 마스터는 =실비×0.1 수식 셀이다
) as v(module_name, item_name, price)
where c.task_type = '마케팅'
  and c.is_current
  and c.module_name = v.module_name
  and c.item_name = v.item_name
  and c.entity_id = (select id from entity_templates where name = '테스티파이');

