-- 사용자 지적(2026-08-20): "금액이 안 맞아 미치겠다. 사용자는 보통 단가를 100만원/10만원
-- 단위로만 맞추고, 그래서 공급가액도 3,000,000처럼 딱 떨어지고 부가세 포함 총액까지 떨어진다."
--
-- 근본 원인은 018 마이그레이션의 전제였다 — "단가는 저장하지 않고, 배분금액 ÷ (작업일×수량)으로
-- 역산한다". 실제 발급본은 정반대 순서로 만들어진다:
--   단가(표준값, 10만원 단위) 고정  →  수량으로 규모 조절  →  공급가액 = 단가 × 수량
-- 그래서 실제 견적서의 모든 금액이 예외 없이 떨어진다. 근거:
--   * data/02. (테스티파이) 우유곳간 시장검증 및 마케팅 견적서_260521.xlsx
--     — 단가 200,000 / 1,000,000, 수량 1·3·12, 합계 8,800,000 → VAT 880,000 → 9,680,000
--   * data/02. (테스티파이) 우유곳간 마케팅 견적서_260709.xlsx
--     — 단가 200,000~2,000,000, 소계 8,000,000 / 2,200,000 / 3,000,000 / 4,800,000
--   * backend/templates/testify.xlsx 시트 "시장성테스트" X13:X21
--     — 260811 우유곳간 발급본의 단가가 마스터에 그대로 남아 있다(039가 이 파일을 양식으로 채택).
--
-- unit_price를 채운 항목은 pdf_service가 그 단가를 고정하고 수량으로 금액을 맞춘다.
-- null인 항목은 지금까지처럼 배분금액에서 역산한다 — 040(module_weight)과 같은 점진 방식으로,
-- 실제 발급본에서 확인된 항목부터 하나씩 정확해진다.

alter table item_catalogs add column unit_price numeric(12, 0);
comment on column item_catalogs.unit_price is
    '표준 단가(원). 실제 발급본에서 확인된 값만 채운다. 채워져 있으면 견적 생성 시 이 단가를
     고정하고 수량으로 총액을 맞춘다(공급가액 = 단가 × 수량). null이면 배분금액에서 역산한다
     (2026-08-20)';

